#!/usr/bin/env python3
"""Generates src/nc_icon.h — the application icon embedded into the exe.

The icon is a 256x256 PNG (base64 encoded in the header) so the program needs
no external files and no resource compiler on any toolchain.

    python3 tools/make_icon.py
"""

import base64
import io
import math
import os

from PIL import Image, ImageDraw, ImageFilter

SIZE = 256
SS = 4  # supersampling

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "nc_icon.h")


def radial(size, stops, center, radius):
    """stops: list of (position 0..1, (r,g,b,a))."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    steps = 512
    cx, cy = center
    for i in range(steps, 0, -1):
        t = i / steps
        r = radius * t
        colour = stops[0][1]
        for pos, next_colour in stops:
            pass
        # interpolate
        prev = stops[0]
        for idx in range(1, len(stops)):
            if t <= stops[idx][0]:
                p0, c0 = prev
                p1, c1 = stops[idx]
                k = 0 if p1 == p0 else (t - p0) / (p1 - p0)
                colour = tuple(int(c0[j] + (c1[j] - c0[j]) * k) for j in range(4))
                break
            prev = stops[idx]
        else:
            colour = stops[-1][1]
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=colour)
    return img


def build():
    n = SIZE * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    # Plate
    plate = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    pd = ImageDraw.Draw(plate)
    steps = n
    for y in range(steps):
        t = y / (steps - 1)
        c = (
            int(0x2C + (0x14 - 0x2C) * t),
            int(0x1D + (0x0F - 0x1D) * t),
            int(0x52 + (0x28 - 0x52) * t),
            255,
        )
        pd.line([(0, y), (n, y)], fill=c)
    mask = Image.new("L", (n, n), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, n - 1, n - 1], radius=int(n * 0.24), fill=255)
    img.paste(plate, (0, 0), mask)

    # Violet halo behind the orb
    halo = radial(n, [(0.0, (124, 77, 255, 150)), (0.55, (90, 45, 200, 60)),
                      (1.0, (60, 25, 140, 0))], (n / 2, n / 2), int(n * 0.46))
    img = Image.alpha_composite(img, halo)
    d = ImageDraw.Draw(img)

    # Orb body
    orb_r = int(n * 0.235)
    cx, cy = n / 2, n / 2
    orb = radial(n, [(0.0, (238, 226, 255, 255)), (0.35, (183, 155, 255, 255)),
                     (0.75, (124, 77, 255, 255)), (1.0, (58, 30, 138, 255))],
                 (cx - orb_r * 0.25, cy - orb_r * 0.35), int(orb_r * 1.7))
    orb_mask = Image.new("L", (n, n), 0)
    ImageDraw.Draw(orb_mask).ellipse([cx - orb_r, cy - orb_r, cx + orb_r, cy + orb_r], fill=255)
    img.paste(orb, (0, 0), orb_mask)

    # Orbit ring
    ring = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    rd = ImageDraw.Draw(ring)
    rd.ellipse([cx - int(n * 0.365), cy - int(n * 0.365), cx + int(n * 0.365), cy + int(n * 0.365)],
               outline=(199, 174, 255, 190), width=max(1, int(n * 0.016)))
    ring = ring.filter(ImageFilter.GaussianBlur(n * 0.004))
    # Fade the ring towards the bottom so it reads as an orbit.
    fade = Image.new("L", (n, n), 0)
    ImageDraw.Draw(fade).polygon([(0, 0), (n, 0), (n, int(n * 0.72)), (0, int(n * 0.86))], fill=255)
    ring.putalpha(Image.composite(ring.getchannel("A"), Image.new("L", (n, n), 0), fade))
    img = Image.alpha_composite(img, ring)

    # Sparkle highlight
    hl = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    hd = ImageDraw.Draw(hl)
    hx, hy = cx - orb_r * 0.38, cy - orb_r * 0.42
    hr = orb_r * 0.20
    hd.ellipse([hx - hr, hy - hr, hx + hr, hy + hr], fill=(255, 255, 255, 210))
    hl = hl.filter(ImageFilter.GaussianBlur(n * 0.006))
    img = Image.alpha_composite(img, hl)

    return img.resize((SIZE, SIZE), Image.LANCZOS)


def main():
    icon = build()
    buffer = io.BytesIO()
    icon.save(buffer, format="PNG", optimize=True)
    data = buffer.getvalue()
    encoded = base64.b64encode(data).decode("ascii")

    lines = []
    for i in range(0, len(encoded), 96):
        lines.append('    "%s"' % encoded[i:i + 96])

    header = """// NOCTURNE Key Pass — embedded application icon.
// Generated by tools/make_icon.py — do not edit by hand.
//
// The PNG is stored base64 encoded so every toolchain (MSVC, MinGW, Zig) can
// embed the icon without a resource compiler.

#pragma once

#include <cstddef>
#include <vector>

namespace nc {

// Base64 of a %d x %d icon PNG (%d bytes).
inline const char* iconPngBase64() {
    return
%s;
}

// Decodes the embedded icon once and returns it. Never fails on well formed
// input; returns an empty vector if the data was damaged.
inline std::vector<unsigned char> iconPngBytes() {
    static const std::vector<unsigned char> cached = [] {
        static const signed char table[256] = {
%s
        };
        const char* text = iconPngBase64();
        std::vector<unsigned char> out;
        int accumulator = 0;
        int bits = 0;
        for (const char* p = text; *p != '\\0'; ++p) {
            const signed char value = table[static_cast<unsigned char>(*p)];
            if (value < 0) continue;  // whitespace or padding
            accumulator = (accumulator << 6) | value;
            bits += 6;
            if (bits >= 8) {
                bits -= 8;
                out.push_back(static_cast<unsigned char>((accumulator >> bits) & 0xFF));
            }
        }
        return out;
    }();
    return cached;
}

}  // namespace nc
""" % (
        SIZE,
        SIZE,
        len(data),
        "\n".join(lines),
        _table_text(),
    )

    path = os.path.abspath(OUT)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(header)
    print("wrote", path, len(data), "bytes of PNG ->", os.path.getsize(path), "bytes of header")


def _table_text():
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    values = ["-1"] * 256
    for index, char in enumerate(alphabet):
        values[ord(char)] = str(index)
    rows = []
    for i in range(0, 256, 16):
        rows.append("        " + ", ".join(values[i:i + 16]))
    return ",\n".join(rows)


if __name__ == "__main__":
    main()
